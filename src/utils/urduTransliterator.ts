// Fallback phonetic transliteration for single words not in dictionary
function transliterateWordPhonetic(word: string): string {
  const clean = word.toLowerCase().trim();
  if (!clean) return '';
  if (NAME_DICTIONARY[clean]) {
    return NAME_DICTIONARY[clean];
  }

  // Multi-character phonetic replacements
  let str = clean;
  const multiMap: [RegExp, string][] = [
    [/^short/g, 'شارٹ'],
    [/^long/g, 'لانگ'],
    [/^grain/g, 'گرین'],
    [/^faj/g, 'فجر'],
    [/^aa/g, 'آ'],
    [/^a/g, 'ا'],
    [/^ee/g, 'ای'],
    [/^oo/g, 'او'],
    [/kh/g, 'خ'],
    [/gh/g, 'غ'],
    [/sh/g, 'ش'],
    [/ch/g, 'چ'],
    [/th/g, 'تھ'],
    [/ph/g, 'پھ'],
    [/bh/g, 'بھ'],
    [/dh/g, 'دھ'],
    [/jh/g, 'جھ'],
    [/rh/g, 'ڑھ'],
    [/aa/g, 'ا'],
    [/ee/g, 'ی'],
    [/oo/g, 'و'],
    [/ou/g, 'و'],
    [/ai/g, 'ائی'],
    [/ay/g, 'ے'],
    [/ck/g, 'ک'],
    [/qu/g, 'ق'],
  ];

  for (const [pattern, repl] of multiMap) {
    str = str.replace(pattern, repl);
  }

  // Single characters (retroflex t -> ٹ and d -> ڈ for English/Roman loanwords)
  const charMap: Record<string, string> = {
    a: 'ا',
    b: 'ب',
    p: 'پ',
    t: 'ٹ',
    j: 'ج',
    c: 'ک',
    d: 'ڈ',
    r: 'ر',
    z: 'ز',
    s: 'س',
    f: 'ف',
    q: 'ق',
    k: 'ک',
    g: 'گ',
    l: 'ل',
    m: 'م',
    n: 'ن',
    w: 'و',
    v: 'و',
    h: 'ہ',
    y: 'ی',
    i: 'ی',
    e: 'ے',
    u: 'و',
    o: 'و',
    x: 'کس',
  };

  let result = '';
  for (let i = 0; i < str.length; i++) {
    const char = str[i];
    result += charMap[char] || char;
  }

  return result;
}

